/**
 * Safely escapes characters that have special meaning in HTML
 * Prevents Stored XSS in web pages and parsing entity errors in Telegram HTML mode
 */
export function escapeHtml(str: string | null | undefined): string {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
